        // 数据库配置 - DataPlatform 库
        config.put("DP_HOST", "${DP_HOST:localhost}");
        config.put("DP_PORT", "${DP_PORT:3306}");
        config.put("DP_NAME", "${DP_NAME:dp}");
        config.put("DP_USER", "${DP_USER:root}");
        config.put("DP_PASSWORD", "${DP_PASSWORD:}");
        
        // 数据库配置 - 对话存储库
        config.put("CONVERSATION_DB_HOST", "${CONVERSATION_DB_HOST:localhost}");
        config.put("CONVERSATION_DB_PORT", "${CONVERSATION_DB_PORT:3306}");
        config.put("CONVERSATION_DB_NAME", "${CONVERSATION_DB_NAME:conversation_db}");
        config.put("CONVERSATION_DB_USER", "${CONVERSATION_DB_USER:root}");
