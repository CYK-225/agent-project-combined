    /**
     * 清除配置缓存
     *
     * @param repoUrl Git 仓库地址，null 表示清除所有
     */
    public void clearCache(String repoUrl) {
        if (repoUrl == null || repoUrl.isBlank()) {
            configCache.clear();
            log.info("Cleared all config cache");
        } else {
            configCache.entrySet().removeIf(entry -> entry.getKey().startsWith(repoUrl + ":"));
            log.info("Cleared config cache for repo: {}", repoUrl);
        }
    }

    /**
     * 更新配置（用于动态刷新）
     *
     * @param repoUrl Git 仓库地址
     * @param envName 环境名称
     * @param config  新配置
     */
    public void updateConfig(String repoUrl, String envName, Map<String, String> config) {
        String cacheKey = repoUrl + ":" + (envName != null ? envName : "default");
        configCache.put(cacheKey, new ConcurrentHashMap<>(config));
        log.info("Updated config for: {}", cacheKey);
    }
